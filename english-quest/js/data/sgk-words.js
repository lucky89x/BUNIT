// Ghép từ trong sách vào từng Unit (từ trùng với từ đã có thì dùng lại, không tạo bản sao)
(function () {
  const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
  let added = 0, linked = 0;
  Object.keys(EQ.SGK_RAW).forEach(book => {
    Object.keys(EQ.SGK_RAW[book]).forEach(n => {
      const unit = (EQ.CURRICULUM[book] || []).find(u => u.n === +n);
      if (!unit) return;
      unit.sgk = [];
      EQ.SGK_RAW[book][n].split('\n').forEach(line => {
        const m = line.match(/^(.+?)\s*=\s*(.+)$/);
        if (!m) return;
        const en = m[1].trim(), vi = m[2].trim();
        let w = EQ.VOCAB.find(x => x.en.toLowerCase() === en.toLowerCase() && !x.custom);
        if (w) { linked++; }
        else {
          const id = 's' + book.slice(2) + '_' + slug(en);
          if (EQ.V[id]) { w = EQ.V[id]; }
          else {
            w = { id, en, vi, e: '📘', ex: '', exVi: '', t: unit.id, r: 'book', pic: false, book, unit: unit.n, sgk: true };
            EQ.VOCAB.push(w); EQ.V[id] = w; added++;
          }
        }
        if (unit.sgk.indexOf(w.id) < 0) unit.sgk.push(w.id);
      });
    });
  });
  EQ.SGK_STATS = { added, linked };
})();
